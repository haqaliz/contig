"""Version pinning from a traced nf-core execution (C8-24).

`versions.yml` is emitted per process under the run's Nextflow work dir; these
tests pin the narrow two-level parser, the work-dir collector, and the rule for
a tool reported with different versions by different processes.
"""

from contig.models import LaunchManifest
from contig.versions import collect_tool_versions, parse_versions_yml


# A real-shaped block, copied from runs/realtest/work/*/versions.yml.
_REAL = (
    '"NFCORE_RNASEQ:RNASEQ:BAM_QC_RNASEQ:DUPRADAR":\n'
    "    bioconductor-dupradar: 1.38.0\n"
    "NFCORE_RNASEQ:PREPARE_GENOME:CUSTOM_GTFFILTER:\n"
    "  python: 3.12.12\n"
)


def test_parse_real_shaped_versions_yml():
    assert parse_versions_yml(_REAL) == {
        "bioconductor-dupradar": "1.38.0",
        "python": "3.12.12",
    }


def test_parse_ignores_comments_blank_lines_and_malformed_rows():
    text = (
        "# generated by nf-core\n"
        "\n"
        "PROCESS_A:\n"
        "    samtools: 1.19.2\n"
        "    no-colon-here\n"
    )
    assert parse_versions_yml(text) == {"samtools": "1.19.2"}


def test_collect_lists_duplicate_tool_versions_instead_of_collapsing(tmp_path):
    # Two processes ran different samtools containers. Neither value is a guess
    # about which one "won", so both are kept, sorted -- never silently collapsed.
    work = tmp_path / "work"
    for task, version in (("ab/cdef", "1.21"), ("12/3456", "1.19.2")):
        task_dir = work / task
        task_dir.mkdir(parents=True)
        (task_dir / "versions.yml").write_text(
            f"PROCESS_{version.replace('.', '_')}:\n    samtools: {version}\n"
        )

    assert collect_tool_versions(work) == {"samtools": "1.19.2, 1.21"}


def test_collect_same_version_twice_collapses(tmp_path):
    work = tmp_path / "work"
    for task in ("ab/cdef", "12/3456"):
        task_dir = work / task
        task_dir.mkdir(parents=True)
        (task_dir / "versions.yml").write_text("P:\n    python: 3.12.12\n")

    assert collect_tool_versions(work) == {"python": "3.12.12"}


def test_collect_absent_or_unreadable_work_dir_is_empty(tmp_path):
    assert collect_tool_versions(tmp_path / "missing") == {}
    assert collect_tool_versions("s3://bucket/work") == {}


def test_launch_manifest_carries_tool_versions_and_legacy_json_loads():
    manifest = LaunchManifest(
        run_id="r1",
        pipeline="nf-core/rnaseq",
        revision="3.26.0",
        profiles=["docker"],
        backend="local",
        container_runtime="docker",
        created_at="2026-10-21T00:00:00Z",
        tool_versions={"samtools": "1.19.2"},
    )
    assert (
        LaunchManifest.model_validate_json(manifest.model_dump_json()).tool_versions
        == {"samtools": "1.19.2"}
    )

    legacy = manifest.model_dump()
    legacy.pop("tool_versions")
    assert LaunchManifest.model_validate(legacy).tool_versions == {}


def _run_record():
    from contig.models import ExecutionTarget, RunRecord, TaskEvent

    return RunRecord(
        run_id="r1",
        pipeline="nf-core/rnaseq",
        pipeline_revision="3.26.0",
        target=ExecutionTarget(
            backend="local", container_runtime="docker", work_dir="w"
        ),
        input_checksums={},
        events=[TaskEvent(process="X", status="COMPLETED", exit=0)],
    )


def test_methods_renders_traced_tool_versions_only_when_present():
    from contig.methods import render_methods

    assert "traced tool versions" not in render_methods(_run_record())

    text = render_methods(_run_record(), tool_versions={"samtools": "1.19.2"})
    assert "traced tool versions (samtools 1.19.2)" in text
